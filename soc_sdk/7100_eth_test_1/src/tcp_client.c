static void stats_buffer(char *outString, double data, enum measure_t type)
{
    int conv = KCONV_UNIT;
    const char *format;
    double unit = (type == SPEED) ? 1000.0 : 1024.0;

    while (data >= unit && conv <= KCONV_GIGA) {
        data /= unit;
        conv++;
    }

    if (data < 9.995) {
        format = "%4.2f %c";
    } else if (data < 99.95) {
        format = "%4.1f %c";
    } else {
        format = "%4.0f %c";
    }
    sprintf(outString, format, data, kLabel[conv]);
}

static void tcp_conn_report(u64_t diff, enum report_type report_type)
{
    u64_t total_len;
    double duration, bandwidth = 0;
    char data[16], perf[16], time[64];

    if (report_type == INTER_REPORT) {
        total_len = client.i_report.total_bytes;
    } else {
        client.i_report.last_report_time = 0;
        total_len = client.total_bytes;
    }

    duration = diff / 1000.0;
    if (duration) {
        bandwidth = (total_len / duration) * 8.0;
    }

    stats_buffer(data, total_len, BYTES);
    stats_buffer(perf, bandwidth, SPEED);
    sprintf(time, "%4.1f-%4.1f sec",
            (double)client.i_report.last_report_time,
            (double)(client.i_report.last_report_time + duration));

    xil_printf("[%3d] %s  %sBytes  %sbits/sec\n\r",
               client.client_id, time, data, perf);

    if (report_type == INTER_REPORT) {
        client.i_report.last_report_time += duration;
    }
}

static void tcp_client_close(struct tcp_pcb *pcb)
{
    err_t err;

    if (pcb != NULL) {
        tcp_sent(pcb, NULL);
        tcp_recv(pcb, NULL);
        tcp_err(pcb, NULL);
        err = tcp_close(pcb);
        if (err != ERR_OK) {
            tcp_abort(pcb);
        }
    }
}

static void uav_reset_stream_state(void)
{
    /*
     * STOP order matters:
     *   1) disable PL stream source in every clock domain;
     *   2) wait for the enable level to cross CDC and clear capture FSMs;
     *   3) abort/reset the S2MM channel and restore its interrupt enables;
     *   4) clear software state.
     */
    (void)mode3_disable_stream();
    fdma_wr_set(UAV_PL_START_LOW);
    usleep(UAV_PL_STOP_SETTLE_US);

    if (g_hw_inited) {
        (void)DMA_RxRecover(&AxiDma);
    } else {
        DMA_Clear_Flags();
    }

    tcp_trans_start = 0;
    first_trans_start = 0;
    g_dma_busy = 0;
    g_frame_ready = 0;
    g_tcp_frame_active = 0;
    g_tcp_frame_offset = 0;
    g_tcp_frame_total_bytes = 0;
    g_last_frame_start_ms = 0;
    g_dma_start_ms = 0;
    g_dma_last_warn_ms = 0;
    g_stream_mode = UAV_MODE_IDLE;
    g_mode1_frame_active = 0;
    g_mode1_frame_offset = 0;
    g_mode1_frame_total_bytes = 0;
    g_mode1_last_frame_ms = 0;
    g_mode1_dma_busy = 0;
    g_mode1_dma_ready = 0;
    g_mode1_dma_start_ms = 0;
    g_mode1_dma_last_warn_ms = 0;
}

static void tcp_client_err(void *arg, err_t err)
{
    LWIP_UNUSED_ARG(arg);
    LWIP_UNUSED_ARG(err);

    u64_t now = get_time_ms();
    u64_t diff_ms = now - client.start_time;

    c_pcb = NULL;
    request_pcb = NULL;
    client_connected = 0;
    uav_reset_stream_state();

    tcp_conn_report(diff_ms, TCP_ABORTED_REMOTE);
    xil_printf("TCP connection aborted\n\r");
}

static void uav_crc32_init(void)
{
    u32 i, j, c;

    for (i = 0; i < 256; i++) {
        c = i;
        for (j = 0; j < 8; j++) {
            if (c & 1U) {
                c = 0xEDB88320U ^ (c >> 1);
            } else {
                c = c >> 1;
            }
        }
        g_crc_table[i] = c;
    }

    g_crc_table_ready = 1;
}

static u32 uav_crc32(const u8 *data, u32 len)
{
    u32 crc = 0xFFFFFFFFU;
    u32 i;

    if (!g_crc_table_ready) {
        uav_crc32_init();
    }

    for (i = 0; i < len; i++) {
        crc = g_crc_table[(crc ^ data[i]) & 0xFFU] ^ (crc >> 8);
    }

    return crc ^ 0xFFFFFFFFU;
}


static void uav_fill_mode1_header(u8 *payload)
{
    g_mode2_header->magic          = UAV_MAGIC_MODE1;
    g_mode2_header->version        = (u16)UAV_PROTOCOL_VERSION;
    g_mode2_header->header_len     = (u16)sizeof(uav_mode2_header_t);
    g_mode2_header->mode           = UAV_MODE1_WORK;
    g_mode2_header->frame_seq      = g_frame_seq;
    g_mode2_header->sample_rate_hz = UAV_SAMPLE_RATE_HZ;
    g_mode2_header->rows           = UAV_MODE1_RX_POINTS;   /* rx_count */
    g_mode2_header->cols           = UAV_MODE1_JAM_POINTS;  /* jam_count */
    g_mode2_header->iq_format      = UAV_IQ_FORMAT_INT16;
    g_mode2_header->payload_bytes  = UAV_MODE1_PAYLOAD_BYTES;
    g_mode2_header->crc32          = uav_crc32(payload, UAV_MODE1_PAYLOAD_BYTES);
    g_mode2_header->reserved0      = (u32)get_time_ms();    /* rx timestamp/debug */
    g_mode2_header->reserved1      = (u32)get_time_ms();    /* jam timestamp/debug */
}

static err_t uav_send_mode1_stream(struct tcp_pcb *tpcb)
{
    err_t err;
    u32 sent_this_call = 0U;
    u32 max_writes_per_call = 8U;
    const u32 header_bytes = (u32)sizeof(uav_mode2_header_t);

    if (tpcb == NULL) {
        return ERR_CONN;
    }
    if (!tcp_trans_start || g_stream_mode != UAV_MODE1_WORK) {
        return ERR_OK;
    }

    /* Arm one DMA/event request at the configured maximum pacing rate.
     * PL may wait indefinitely until a positive RX frame and the corresponding
     * selected jammer segment are both available.
     */
    if (!g_mode1_dma_busy && !g_mode1_dma_ready && !g_mode1_frame_active) {
        u64_t now = get_time_ms();
        if ((g_mode1_last_frame_ms == 0U) ||
            ((now - g_mode1_last_frame_ms) >= UAV_MODE1_FRAME_PERIOD_MS)) {
            (void)uav_start_mode1_dma_frame();
        }
    }

    uav_poll_mode1_dma_done();
    uav_begin_mode1_tcp_send_frame();

    while (g_mode1_frame_active && max_writes_per_call--) {
        u16_t snd_avail;
        u32 remain_total;
        u32 chunk;
        const u8 *ptr;
        u8_t flags;

        snd_avail = tcp_sndbuf(tpcb);
        if (snd_avail < UAV_TCP_MIN_WRITE_BYTES) {
            break;
        }

        remain_total = g_mode1_frame_total_bytes - g_mode1_frame_offset;
        if (g_mode1_frame_offset < header_bytes) {
            u32 header_remain = header_bytes - g_mode1_frame_offset;
            ptr = ((const u8 *)g_mode2_header) + g_mode1_frame_offset;
            chunk = header_remain;
        } else {
            u32 payload_offset = g_mode1_frame_offset - header_bytes;
            u32 payload_remain = UAV_MODE1_PAYLOAD_BYTES - payload_offset;
            ptr = g_mode1_payload + payload_offset;
            chunk = payload_remain;
        }

        if (chunk > UAV_TCP_CHUNK_BYTES) {
            chunk = UAV_TCP_CHUNK_BYTES;
        }
        if (chunk > snd_avail) {
            chunk = snd_avail;
        }
        if (chunk > remain_total) {
            chunk = remain_total;
        }
        if (chunk == 0U) {
            break;
        }

        flags = TCP_WRITE_FLAG_COPY;
        if (chunk < remain_total) {
            flags |= TCP_WRITE_FLAG_MORE;
        }

        err = tcp_write(tpcb, ptr, (u16_t)chunk, flags);
        if (err != ERR_OK) {
            if (err != ERR_MEM) {
                xil_printf("Mode1 tcp_write error: %d\r\n", err);
            }
            break;
        }

        g_mode1_frame_offset += chunk;
        client.total_bytes += chunk;
        client.i_report.total_bytes += chunk;
        sent_this_call += chunk;

        if (g_mode1_frame_offset >= g_mode1_frame_total_bytes) {
            g_mode1_frame_active = 0U;
            g_mode1_last_frame_ms = get_time_ms();
            xil_printf("Mode1 frame %lu sent, crc=0x%08lx\r\n",
                       (unsigned long)g_frame_seq,
                       (unsigned long)g_mode2_header->crc32);
            g_frame_seq++;
            break;
        }
    }

    if (sent_this_call > 0U) {
        err = tcp_output(tpcb);
        if (err != ERR_OK) {
            xil_printf("Mode1 tcp_output error: %d\r\n", err);
            return err;
        }
    }

    if (client.i_report.report_interval_time) {
        u64_t now = get_time_ms();
        if (client.i_report.start_time) {
            u64_t diff_ms = now - client.i_report.start_time;
            if (diff_ms >= client.i_report.report_interval_time) {
                tcp_conn_report(diff_ms, INTER_REPORT);
                client.i_report.start_time = now;
                client.i_report.total_bytes = 0;
            }
        } else {
            client.i_report.start_time = now;
        }
    }

    return ERR_OK;
}

static err_t uav_send_active_stream(struct tcp_pcb *tpcb)
{
    if (g_stream_mode == UAV_MODE1_WORK) {
        return uav_send_mode1_stream(tpcb);
    }
    if (g_stream_mode == UAV_MODE2_INFER) {
        return uav_send_mode2_stream(tpcb);
    }
    return ERR_OK;
}

static void uav_fill_mode2_header(u8 *payload)
{
    g_mode2_header->magic          = UAV_MAGIC_MODE2;
    g_mode2_header->version        = (u16)UAV_PROTOCOL_VERSION;
    g_mode2_header->header_len     = (u16)sizeof(uav_mode2_header_t);
    g_mode2_header->mode           = UAV_MODE2_INFER;
    g_mode2_header->frame_seq      = g_frame_seq;
    g_mode2_header->sample_rate_hz = UAV_SAMPLE_RATE_HZ;
    g_mode2_header->rows           = UAV_MODE2_ROWS;
    g_mode2_header->cols           = UAV_MODE2_COLS;
    g_mode2_header->iq_format      = UAV_IQ_FORMAT_INT16;
    g_mode2_header->payload_bytes  = UAV_MODE2_PAYLOAD_BYTES;
    g_mode2_header->crc32          = uav_crc32(payload, UAV_MODE2_PAYLOAD_BYTES);
    g_mode2_header->reserved0      = (u32)get_time_ms();
    g_mode2_header->reserved1      = 0U;
}

static int uav_start_mode2_dma_frame(void)
{
    int Status;
    u8 *buf;

    if (g_dma_busy || g_frame_ready || g_tcp_frame_active) {
        return XST_SUCCESS;
    }

    /* Select PL source = Mode2 event generator before arming DMA. */
    (void)mode3_set_stream_mode(UAV_PL_STREAM_MODE_MODE2);

    Status = uav_prepare_dma_channel();
    if (Status != XST_SUCCESS) {
        return Status;
    }

    buf = g_dma_buf[g_dma_buf_index];

    /* S2MM destination buffer: invalidate before and after DMA. */
    Xil_DCacheInvalidateRange((UINTPTR)buf, UAV_MODE2_PAYLOAD_BYTES);

    Status = XAxiDma_SimpleTransfer(&AxiDma,
                                    (UINTPTR)buf,
                                    UAV_MODE2_PAYLOAD_BYTES,
                                    XAXIDMA_DEVICE_TO_DMA);
    if (Status != XST_SUCCESS) {
        xil_printf("XAxiDma_SimpleTransfer S2MM failed: %d\r\n", Status);
        return Status;
    }

    g_payload_to_send = buf;
    g_dma_busy = 1U;
    g_dma_start_ms = get_time_ms();
    g_dma_last_warn_ms = g_dma_start_ms;

    /* DMA receive must be armed before PL starts AXI-Stream output. */
    uav_pl_start_pulse();

    xil_printf("Mode2 DMA frame %lu started, buf=0x%08lx\r\n",
               (unsigned long)g_frame_seq, (unsigned long)((UINTPTR)buf));
    return XST_SUCCESS;
}

static void uav_poll_dma_done(void)
{
    u64_t now;

    if (!g_dma_busy) {
        return;
    }

    if (g_dma_error) {
        xil_printf("Mode2 DMA error detected: irq=0x%08lx, s2mm_dmasr=0x%08lx\r\n",
                   (unsigned long)g_dma_last_irq_status,
                   (unsigned long)g_dma_last_rx_status);

        (void)mode3_disable_stream();
        fdma_wr_set(UAV_PL_START_LOW);
        usleep(UAV_PL_STOP_SETTLE_US);
        (void)DMA_RxRecover(&AxiDma);

        g_dma_busy = 0U;
        g_frame_ready = 0U;
        g_last_frame_start_ms = get_time_ms();

        if (tcp_trans_start && g_stream_mode == UAV_MODE2_INFER) {
            (void)mode3_set_stream_mode(UAV_PL_STREAM_MODE_MODE2);
            usleep(UAV_PL_MODE_SETTLE_US);
        }
        return;
    }

    if (g_dma_rx_done) {
        Xil_DCacheInvalidateRange((UINTPTR)g_payload_to_send, UAV_MODE2_PAYLOAD_BYTES);
        uav_fill_mode2_header(g_payload_to_send);

        g_dma_busy = 0U;
        g_frame_ready = 1U;
        DMA_Clear_Flags();

        xil_printf("Mode2 DMA frame %lu done, crc=0x%08lx\r\n",
                   (unsigned long)g_frame_seq,
                   (unsigned long)g_mode2_header->crc32);
        return;
    }

    now = get_time_ms();
    if ((now - g_dma_last_warn_ms) >= 1000U) {
        g_dma_last_warn_ms = now;
        xil_printf("INFO: Mode2 DMA frame %lu has waited %lu ms for the next positive detection snapshot. "
                   "This is normal when no target is detected.\r\n",
                   (unsigned long)g_frame_seq,
                   (unsigned long)(now - g_dma_start_ms));
    }
}

static void uav_begin_tcp_send_frame(void)
{
    if (!g_frame_ready || g_tcp_frame_active) {
        return;
    }

    g_tcp_frame_offset = 0U;
    g_tcp_frame_total_bytes = sizeof(uav_mode2_header_t) + UAV_MODE2_PAYLOAD_BYTES;
    g_tcp_frame_active = 1U;
    g_frame_ready = 0U;
}

static err_t uav_send_mode2_stream(struct tcp_pcb *tpcb)
{
    err_t err;
    u32 sent_this_call = 0U;
    u32 max_writes_per_call = 8U;
    const u32 header_bytes = (u32)sizeof(uav_mode2_header_t);

    if (tpcb == NULL) {
        return ERR_CONN;
    }

    if (!tcp_trans_start || g_stream_mode != UAV_MODE2_INFER) {
        return ERR_OK;
    }

    if (!g_dma_busy && !g_frame_ready && !g_tcp_frame_active) {
        u64_t now = get_time_ms();
        if ((g_last_frame_start_ms == 0U) ||
            ((now - g_last_frame_start_ms) >= UAV_MODE2_FRAME_PERIOD_MS)) {
            g_last_frame_start_ms = now;
            (void)uav_start_mode2_dma_frame();
        }
    }

    uav_poll_dma_done();
    uav_begin_tcp_send_frame();

    while (g_tcp_frame_active && max_writes_per_call--) {
        u16_t snd_avail;
        u32 remain_total;
        u32 chunk;
        const u8 *ptr;
        u8_t flags;

        snd_avail = tcp_sndbuf(tpcb);
        if (snd_avail < UAV_TCP_MIN_WRITE_BYTES) {
            break;
        }

        remain_total = g_tcp_frame_total_bytes - g_tcp_frame_offset;

        /* Header and payload are in different DDR regions; never cross boundary. */
        if (g_tcp_frame_offset < header_bytes) {
            u32 header_remain = header_bytes - g_tcp_frame_offset;
            ptr = ((const u8 *)g_mode2_header) + g_tcp_frame_offset;
            chunk = header_remain;
        } else {
            u32 payload_offset = g_tcp_frame_offset - header_bytes;
            u32 payload_remain = UAV_MODE2_PAYLOAD_BYTES - payload_offset;
            ptr = g_payload_to_send + payload_offset;
            chunk = payload_remain;
        }

        if (chunk > UAV_TCP_CHUNK_BYTES) {
            chunk = UAV_TCP_CHUNK_BYTES;
        }
        if (chunk > snd_avail) {
            chunk = snd_avail;
        }
        if (chunk > remain_total) {
            chunk = remain_total;
        }
        if (chunk == 0U) {
            break;
        }

        flags = TCP_WRITE_FLAG_COPY;
        if (chunk < remain_total) {
            flags |= TCP_WRITE_FLAG_MORE;
        }

        err = tcp_write(tpcb, ptr, (u16_t)chunk, flags);
        if (err != ERR_OK) {
            if (err != ERR_MEM) {
                xil_printf("tcp_write error: %d\r\n", err);
            }
            break;
        }

        g_tcp_frame_offset += chunk;
        client.total_bytes += chunk;
        client.i_report.total_bytes += chunk;
        sent_this_call += chunk;

        if (g_tcp_frame_offset >= g_tcp_frame_total_bytes) {
            g_tcp_frame_active = 0U;
            g_frame_seq++;
            g_dma_buf_index ^= 1U;
            break;
        }
    }

    if (sent_this_call > 0U) {
        err = tcp_output(tpcb);
        if (err != ERR_OK) {
            xil_printf("tcp_output error: %d\r\n", err);
            return err;
        }
    }

    if (client.i_report.report_interval_time) {
        u64_t now = get_time_ms();
        if (client.i_report.start_time) {
            u64_t diff_ms = now - client.i_report.start_time;
            if (diff_ms >= client.i_report.report_interval_time) {
                tcp_conn_report(diff_ms, INTER_REPORT);
                client.i_report.start_time = now;
                client.i_report.total_bytes = 0;
            }
        } else {
            client.i_report.start_time = now;
        }
    }

    return ERR_OK;
}

static err_t tcp_client_sent(void *arg, struct tcp_pcb *tpcb, u16_t len)
{
    LWIP_UNUSED_ARG(arg);
    LWIP_UNUSED_ARG(len);
    return uav_send_active_stream(tpcb);
}

err_t tcp_recv_callback(void *arg, struct tcp_pcb *tpcb, struct pbuf *p, err_t err)
{
    u32 cmd_net = 0U;
    u32 cmd;

    LWIP_UNUSED_ARG(arg);

    if ((err != ERR_OK) || (p == NULL)) {
        if (p != NULL) {
            pbuf_free(p);
        }
        tcp_client_close(tpcb);
        c_pcb = NULL;
        request_pcb = NULL;
        client_connected = 0;
        uav_reset_stream_state();
        xil_printf("tcp connection closed\r\n");
        return ERR_OK;
    }

    if (p->tot_len >= 4U) {
        pbuf_copy_partial(p, &cmd_net, 4U, 0U);
        cmd = ntohl(cmd_net);

        if (cmd == TCP_START_CMD) {
            if (tcp_trans_start && g_stream_mode == UAV_MODE2_INFER) {
                xil_printf("TCP: Mode2 already start!\r\n");
            } else {
                uav_reset_stream_state();
                tcp_trans_start = 1U;
                g_stream_mode = UAV_MODE2_INFER;
                first_trans_start = 1U;
                g_frame_seq = 0U;       /* keep PL test-source seq aligned after reset */
                g_dma_buf_index = 0U;
                (void)mode3_set_stream_mode(UAV_PL_STREAM_MODE_MODE2);
                usleep(UAV_PL_MODE_SETTLE_US);
                xil_printf("TCP: START Mode2 DMA IQ stream\r\n");
            }
        } else if (cmd == TCP_STOP_CMD) {
            if (!tcp_trans_start || g_stream_mode != UAV_MODE2_INFER) {
                xil_printf("TCP: Mode2 already stop!\r\n");
            } else {
                uav_reset_stream_state();
                xil_printf("TCP: STOP Mode2 stream\r\n");
            }
        } else if (cmd == TCP_START_MODE1_CMD) {
            if (tcp_trans_start && g_stream_mode == UAV_MODE1_WORK) {
                xil_printf("TCP: Mode1 already start!\r\n");
            } else {
                uav_reset_stream_state();
                tcp_trans_start = 1U;
                g_stream_mode = UAV_MODE1_WORK;
                first_trans_start = 1U;
                g_frame_seq = 0U;
                (void)mode3_set_stream_mode(UAV_PL_STREAM_MODE_MODE1);
                usleep(UAV_PL_MODE_SETTLE_US);
                xil_printf("TCP: START Mode1 event stream, RX=%lu pts, JAM=%lu pts, payload=%lu bytes, max %lu FPS\r\n",
                           (unsigned long)UAV_MODE1_RX_POINTS,
                           (unsigned long)UAV_MODE1_JAM_POINTS,
                           (unsigned long)UAV_MODE1_PAYLOAD_BYTES,
                           (unsigned long)UAV_MODE1_FPS);
            }
        } else if (cmd == TCP_STOP_MODE1_CMD) {
            if (!tcp_trans_start || g_stream_mode != UAV_MODE1_WORK) {
                xil_printf("TCP: Mode1 already stop!\r\n");
            } else {
                uav_reset_stream_state();
                xil_printf("TCP: STOP Mode1 stream\r\n");
            }
        } else if (cmd == TCP_MODE3_CTRL_CMD) {
            handle_mode3_ctrl_pbuf(p);
        } else {
            xil_printf("TCP: unknown cmd 0x%08lx, len=%u\r\n",
                       (unsigned long)cmd, (unsigned int)p->tot_len);
        }
    }

    tcp_recved(tpcb, p->tot_len);
    pbuf_free(p);

    return ERR_OK;
}

static err_t tcp_client_connected(void *arg, struct tcp_pcb *tpcb, err_t err)
{
    LWIP_UNUSED_ARG(arg);

    if (err != ERR_OK) {
        tcp_client_close(tpcb);
        xil_printf("Connection error\n\r");
        return err;
    }

    c_pcb = tpcb;

    client.start_time = get_time_ms();
    client.end_time = TCP_TIME_INTERVAL * 1000;
    client.client_id++;
    client.total_bytes = 0;
    client.i_report.report_interval_time = INTERIM_REPORT_INTERVAL * 1000;
    client.i_report.last_report_time = 0;
    client.i_report.start_time = 0;
    client.i_report.total_bytes = 0;

    print_tcp_conn_stats();

    tcp_arg(c_pcb, NULL);
    tcp_sent(c_pcb, tcp_client_sent);
    tcp_recv(c_pcb, tcp_recv_callback);
    tcp_err(c_pcb, tcp_client_err);

    tcp_nagle_disable(c_pcb);
    if (!tcp_nagle_disabled(c_pcb)) {
        xil_printf("tcp nagle disable failed!\r\n");
    }

    client_connected = 1U;
    uav_reset_stream_state();

    xil_printf("TCP connected. Waiting for START command.\r\n");
    return ERR_OK;
}

void transfer_data(void)
{
    if (client.client_id && c_pcb != NULL) {
        (void)uav_send_active_stream(c_pcb);
    }
}

static void app_hw_init(void)
{
    if (g_hw_inited) {
        return;
    }

    RxBufferPtr[0] = (u8 *)(RX_BUFFER0_BASE - HEADER_SIZE);
    RxBufferPtr[1] = (u8 *)(RX_BUFFER1_BASE - HEADER_SIZE);
    RxBufferPtr[2] = (u8 *)(RX_BUFFER2_BASE - HEADER_SIZE);

    RxBufferPtr_DATA[0] = (u8 *)(RX_BUFFER0_BASE);
    RxBufferPtr_DATA[1] = (u8 *)(RX_BUFFER1_BASE);
    RxBufferPtr_DATA[2] = (u8 *)(RX_BUFFER2_BASE);

    tcp_rx_buffer = (u32 *)TCP_RXBUFFER_BASE_ADDR;

#ifdef XPAR_GPIO_USER_RSTN_DEVICE_ID
    if (XGpio_Initialize(&gpio_user_rstn, XPAR_GPIO_USER_RSTN_DEVICE_ID) == XST_SUCCESS) {
        XGpio_SetDataDirection(&gpio_user_rstn, 1, 0x0);
        XGpio_DiscreteWrite(&gpio_user_rstn, 1, UAV_PL_RESET_ASSERT);
        xil_printf("GPIO user_rstn init OK, device_id=%d\r\n", XPAR_GPIO_USER_RSTN_DEVICE_ID);
    } else {
        xil_printf("GPIO user_rstn init FAILED\r\n");
    }
#endif

#ifdef XPAR_GPIO_USER_START_DEVICE_ID
    if (XGpio_Initialize(&gpio_user_start, XPAR_GPIO_USER_START_DEVICE_ID) == XST_SUCCESS) {
        XGpio_SetDataDirection(&gpio_user_start, 1, 0x0);
        XGpio_DiscreteWrite(&gpio_user_start, 1, UAV_PL_START_LOW);
        xil_printf("GPIO user_start init OK, device_id=%d\r\n", XPAR_GPIO_USER_START_DEVICE_ID);
    } else {
        xil_printf("GPIO user_start init FAILED\r\n");
    }
#endif

    /* Initialize Mode3 GPIO if the corresponding AXI-GPIO IPs exist.
     * Failure here does not block Mode2 DMA upload.
     */
    (void)mode3_gpio_init();

    uav_pl_reset_pulse();
    uav_crc32_init();
    g_hw_inited = 1U;
}

void start_application(void)
{
    err_t err;
    ip_addr_t remote_addr;

    app_hw_init();
    first_trans_start = 0U;
    client_connected = 0U;
    uav_reset_stream_state();

#if LWIP_IPV6==1
    remote_addr.type = IPADDR_TYPE_V6;
    err = inet6_aton(TCP_SERVER_IPV6_ADDRESS, &remote_addr);
#else
    err = inet_aton(TCP_SERVER_IP_ADDRESS, &remote_addr);
#endif

    if (!err) {
        xil_printf("Invalid Server IP address: %d\r\n", err);
        return;
    }

    request_pcb = tcp_new_ip_type(IPADDR_TYPE_ANY);
    if (!request_pcb) {
        xil_printf("Error in PCB creation. out of memory\r\n");
        return;
    }

    err = tcp_connect(request_pcb, &remote_addr, TCP_CONN_PORT, tcp_client_connected);
    if (err) {
        xil_printf("Error on tcp_connect: %d\r\n", err);
        tcp_client_close(request_pcb);
        request_pcb = NULL;
        return;
    }

    client.client_id = 0;
}
