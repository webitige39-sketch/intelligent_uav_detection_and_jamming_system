static int uav_start_mode1_dma_frame(void)
{
    int Status;

    if (g_mode1_dma_busy || g_mode1_dma_ready || g_mode1_frame_active) {
        return XST_SUCCESS;
    }

    /* Select PL source = Mode1 event capture before arming DMA. */
    (void)mode3_set_stream_mode(UAV_PL_STREAM_MODE_MODE1);

    Status = uav_prepare_dma_channel();
    if (Status != XST_SUCCESS) {
        return Status;
    }

    /* S2MM destination buffer: invalidate before and after DMA. */
    Xil_DCacheInvalidateRange((UINTPTR)g_mode1_payload, UAV_MODE1_PAYLOAD_BYTES);

    Status = XAxiDma_SimpleTransfer(&AxiDma,
                                    (UINTPTR)g_mode1_payload,
                                    UAV_MODE1_PAYLOAD_BYTES,
                                    XAXIDMA_DEVICE_TO_DMA);
    if (Status != XST_SUCCESS) {
        xil_printf("Mode1 XAxiDma_SimpleTransfer failed: %d\r\n", Status);
        return Status;
    }

    g_mode1_dma_busy = 1U;
    g_mode1_dma_start_ms = get_time_ms();
    g_mode1_dma_last_warn_ms = g_mode1_dma_start_ms;

    /* DMA receive must be armed before PL starts AXI-Stream output. */
    uav_pl_start_pulse();

    xil_printf("Mode1 DMA frame %lu started, buf=0x%08lx, bytes=%lu\r\n",
               (unsigned long)g_frame_seq,
               (unsigned long)((UINTPTR)g_mode1_payload),
               (unsigned long)UAV_MODE1_PAYLOAD_BYTES);
    return XST_SUCCESS;
}

static void uav_poll_mode1_dma_done(void)
{
    u64_t now;

    if (!g_mode1_dma_busy) {
        return;
    }

    if (g_dma_error) {
        xil_printf("Mode1 DMA error detected: irq=0x%08lx, s2mm_dmasr=0x%08lx\r\n",
                   (unsigned long)g_dma_last_irq_status,
                   (unsigned long)g_dma_last_rx_status);

        (void)mode3_disable_stream();
        fdma_wr_set(UAV_PL_START_LOW);
        usleep(UAV_PL_STOP_SETTLE_US);
        (void)DMA_RxRecover(&AxiDma);

        g_mode1_dma_busy = 0U;
        g_mode1_dma_ready = 0U;
        g_mode1_last_frame_ms = get_time_ms();

        if (tcp_trans_start && g_stream_mode == UAV_MODE1_WORK) {
            (void)mode3_set_stream_mode(UAV_PL_STREAM_MODE_MODE1);
            usleep(UAV_PL_MODE_SETTLE_US);
        }
        return;
    }

    if (g_dma_rx_done) {
        Xil_DCacheInvalidateRange((UINTPTR)g_mode1_payload, UAV_MODE1_PAYLOAD_BYTES);
        uav_fill_mode1_header(g_mode1_payload);

        g_mode1_dma_busy = 0U;
        g_mode1_dma_ready = 1U;
        DMA_Clear_Flags();

        xil_printf("Mode1 DMA frame %lu done, crc=0x%08lx\r\n",
                   (unsigned long)g_frame_seq,
                   (unsigned long)g_mode2_header->crc32);
        return;
    }

    now = get_time_ms();
    if ((now - g_mode1_dma_last_warn_ms) >= 1000U) {
        g_mode1_dma_last_warn_ms = now;
        xil_printf("INFO: Mode1 DMA frame %lu has waited %lu ms for the next detected RX+JAM event. "
                   "This is normal when no target is detected.\r\n",
                   (unsigned long)g_frame_seq,
                   (unsigned long)(now - g_mode1_dma_start_ms));
    }
}

